import { PrismaClient } from "@prisma/client";
import { readFileSync } from "node:fs";
import { canonicalSteps as sharedCanonicalSteps } from "../src/lib/demo-portal";
import type { Step } from "../src/lib/schemas";

import { test } from "@playwright/test";

export const db = new PrismaClient();
// An open Prisma connection keeps the worker alive after the last test.
test.afterAll(() => db.$disconnect());
export const DEMO = "http://localhost:3100/demo/invoices";

export const canonicalSteps: Step[] = sharedCanonicalSteps(DEMO);

/** Live-model tests run only with E2E_LIVE=1 and a key in the app's .env (or the environment). */
export function hasModelKey(): boolean {
  if (process.env.E2E_LIVE !== "1") return false;
  try {
    if (/^ANTHROPIC_API_KEY=\S/m.test(readFileSync(".env", "utf8"))) return true;
  } catch {}
  return !!process.env.ANTHROPIC_API_KEY;
}

export async function seedWorkflow(name: string, steps: Step[], status = "needs_approval", recoveryPolicy = "auto_safe") {
  const wf = await db.workflow.create({
    data: {
      name,
      task: "Find unpaid invoices, filter by a minimum amount, and export the matching rows as CSV.",
      startUrl: DEMO,
      allowedPrefixes: JSON.stringify(["http://localhost:3100/demo/"]),
      inputs: JSON.stringify([{ name: "minimumAmount", label: "Minimum amount (USD)", type: "number", default: "1000" }]),
      steps: JSON.stringify(steps),
      planNotes: "Seeded by the E2E suite (not generated by Opus).",
      status,
      recoveryPolicy,
    },
  });
  return wf.id;
}

