export async function setVariant(request: import("@playwright/test").APIRequestContext, variant: "classic" | "redesigned" | "export_removed") {
  const res = await request.post("/api/demo/variant", { data: { variant } });
  if (!res.ok()) throw new Error(`variant switch failed: ${res.status()}`);
}
